interface IconProps {
  name: IconName
  size?: number
  /** Supply when the icon is the only content of a control. */
  title?: string
}

export function Icon({ name, size = 18, title }: IconProps) {
  return (
    <svg
      className="icon"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      /* Decorative unless a title is given: a label beside the icon would
         otherwise be read out twice. */
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      {PATHS[name]}
    </svg>
  )
}
